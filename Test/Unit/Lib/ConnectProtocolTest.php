<?php
declare(strict_types=1);

namespace IntentsFi\Checkout\Test\Unit\Lib;

use IntentsFi\Checkout\Lib\ConnectProtocol;
use PHPUnit\Framework\TestCase;

/**
 * The Connect protocol is not forked: Lib/ConnectProtocol.php is the shared
 * plugins/_shared/connect/class-connect-protocol.php with only its namespace line and class line
 * rewritten (bin/connect-protocol.sh), and it loads by autoload alone: nothing in the module
 * includes a file by path (the Adobe Commerce Marketplace code check refuses require/include).
 */
final class ConnectProtocolTest extends TestCase
{
    private const MODULE = __DIR__ . '/../../..';
    private const GENERATED = self::MODULE . '/Lib/ConnectProtocol.php';
    private const SHARED = self::MODULE . '/../_shared/connect/class-connect-protocol.php';

    public function testItAutoloadsFromTheModuleNamespace(): void
    {
        self::assertTrue(class_exists(ConnectProtocol::class));
        $file = (string) (new \ReflectionClass(ConnectProtocol::class))->getFileName();
        self::assertSame(realpath(self::GENERATED), realpath($file));
    }

    public function testItIsTheSharedProtocolApartFromTheNamespaceAndClassLines(): void
    {
        if (!is_file(self::SHARED)) {
            self::markTestSkipped('Not in the intents.fi repository: no shared protocol to compare with.');
        }
        $shared = file(self::SHARED, FILE_IGNORE_NEW_LINES);
        $generated = file(self::GENERATED, FILE_IGNORE_NEW_LINES);
        self::assertIsArray($shared);
        self::assertIsArray($generated);
        self::assertCount(count($shared), $generated, 'Run bin/connect-protocol.sh.');

        $differ = [];
        foreach ($shared as $i => $line) {
            if ($line !== $generated[$i]) {
                $differ[$line] = $generated[$i];
            }
        }
        self::assertSame([
            'namespace IntentsFi\Connect;' => 'namespace IntentsFi\Checkout\Lib; // Generated by bin/connect-protocol.sh from the shared protocol: do not edit.',
            'class Connect_Protocol {' => 'class ConnectProtocol {',
        ], $differ, 'Lib/ConnectProtocol.php must be generated from the shared protocol: run bin/connect-protocol.sh.');
    }

    public function testNothingTheModuleShipsIncludesAFile(): void
    {
        $found = [];
        $files = new \RecursiveIteratorIterator(
            new \RecursiveDirectoryIterator(realpath(self::MODULE), \FilesystemIterator::SKIP_DOTS)
        );
        foreach ($files as $file) {
            $path = substr((string) $file, strlen((string) realpath(self::MODULE)) + 1);
            // What bin/build-dist.sh leaves out of the zip.
            if (preg_match('#^(dev|bin|Test|marketplace)/|^\.#', $path) || !preg_match('/\.(php|phtml)$/', $path)) {
                continue;
            }
            foreach (token_get_all((string) file_get_contents((string) $file)) as $token) {
                if (is_array($token) && in_array($token[0], [T_REQUIRE, T_REQUIRE_ONCE, T_INCLUDE, T_INCLUDE_ONCE], true)) {
                    $found[] = $path . ':' . $token[2];
                }
            }
        }
        self::assertSame([], $found);
    }
}
