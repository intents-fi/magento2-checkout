#!/usr/bin/env bash
# Generate Lib/ConnectProtocol.php from the shared Connect protocol.
#
#   bin/connect-protocol.sh            # (re)write Lib/ConnectProtocol.php
#   bin/connect-protocol.sh --check    # fail if Lib/ConnectProtocol.php is not what this generates
#
# The plugin half of Connect is one class shared by every store plugin:
# plugins/_shared/connect/class-connect-protocol.php (class IntentsFi\Connect\Connect_Protocol), the
# canonical copy. The module does not fork it and does not include it by path (the Adobe Commerce
# Marketplace code check refuses any require/include): this script copies it into the module's own
# PSR-4 namespace, as IntentsFi\Checkout\Lib\ConnectProtocol, so Composer and Magento's app/code
# autoloader both find it. Exactly two lines change, the namespace line and the class line; nothing
# else is touched. Test/Unit/Lib/ConnectProtocolTest.php checks the same thing from the other side.
#
# bin/build-dist.sh runs this before every build. Outside the intents.fi repository (the module's
# own Git mirror) there is no shared file, and the committed Lib/ConnectProtocol.php is used as is.
set -euo pipefail
cd "$(dirname "$0")/.."

# Overridable so scripts/mirror-magento.sh can check the files of a commit rather than the work tree.
SHARED="${CONNECT_SHARED:-../_shared/connect/class-connect-protocol.php}"
OUT="${CONNECT_OUT:-Lib/ConnectProtocol.php}"
CHECK=0
[ "${1:-}" = "--check" ] && CHECK=1

if [ ! -f "$SHARED" ]; then
  [ -f "$OUT" ] || { echo "no $SHARED and no $OUT" >&2; exit 1; }
  echo "$SHARED not found (not in the intents.fi repository): using the committed $OUT"
  exit 0
fi

TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT
# Exact whole-line matches, each required exactly once. ENVIRON keeps the backslashes literal.
NS_FROM='namespace IntentsFi\Connect;' \
NS_TO='namespace IntentsFi\Checkout\Lib; // Generated by bin/connect-protocol.sh from the shared protocol: do not edit.' \
CLASS_FROM='class Connect_Protocol {' \
CLASS_TO='class ConnectProtocol {' \
awk '
  $0 == ENVIRON["NS_FROM"]    { print ENVIRON["NS_TO"]; ns++; next }
  $0 == ENVIRON["CLASS_FROM"] { print ENVIRON["CLASS_TO"]; cls++; next }
  { print }
  END { if (ns != 1 || cls != 1) { print "expected one namespace line and one class line, found " ns + 0 " and " cls + 0 > "/dev/stderr"; exit 3 } }
' "$SHARED" > "$TMP"

if [ "$CHECK" = 1 ]; then
  cmp -s "$TMP" "$OUT" || { echo "$OUT is not generated from $SHARED: run bin/connect-protocol.sh" >&2; exit 1; }
  echo "$OUT matches $SHARED"
  exit 0
fi

mkdir -p "$(dirname "$OUT")"
if cmp -s "$TMP" "$OUT" 2>/dev/null; then
  echo "$OUT is up to date"
else
  cp "$TMP" "$OUT"
  chmod 0644 "$OUT"
  echo "$OUT regenerated from $SHARED: commit it"
fi
